export function fill(template: string, vars: Vars = {}): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) => vars[key] ?? match);
}

export function message(lang: Lang, code: string, vars?: Vars): Msg {
  const m = messages[lang][code] ?? messages[lang].unknown;
  return { title: fill(m.title, vars), detail: fill(m.detail, { message: code, ...vars }) };
}

export function text(lang: Lang, key: string, vars?: Vars): string {
  return fill(ui[lang][key] ?? key, vars);
}

/** Saved choice, else the browser's language. */
export function pickLang(saved: string | null, browser: readonly string[]): Lang {
  if (saved === "en" || saved === "tr") return saved;
  return browser.some((l) => l.toLowerCase().startsWith("tr")) ? "tr" : "en";
}

export function locale(lang: Lang): string {
  return lang === "tr" ? "tr-TR" : "en-GB";
}
